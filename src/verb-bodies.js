import { EXEC_LANGS, runnerVerb, tableRow } from './verb-table.js'
import { GUEST_ACCEPTED_FIELDS, GUEST_BODY_SOURCE, GUEST_ENVELOPE_FIELDS } from './guest-bodies.js'

export { GUEST_ENVELOPE_FIELDS }

export { EXEC_LANGS }

export const DISPATCH_BODY_FIELDS = {
    lane_wait_ms: { type: 'number', description: 'Serial-lane wait budget in ms, named by a dispatch_starved_waiting_for_serial_lane retry_hint; also lifts the poll timeout to cover it (capped by the poll ceiling).' },
    lean_node: { type: 'string', description: 'gm-graph node this dispatch serves (gm-hop node emission); recorded on the Dream-RSI observation.' },
}

const UNDECLARED_NOTE ='gm-mcp declares no body schema for this verb; send the fields its Rust handler reads and read the refusal when one is wrong.'

const GUEST_LIST_GOVERNS_ONLY_ONE_MODE = new Set(['codesearch'])
const GUEST_FIELD_DESCRIPTION = 'Accepted by the rs-plugkit handler (generated by scripts/gen-guest-bodies.mjs); semantics in skills/gm/docs/verbs.md.'

function guestFields(row) {
    if (!row) return null
    const wire = runnerVerb(row)
    if (GUEST_LIST_GOVERNS_ONLY_ONE_MODE.has(wire)) return null
    return GUEST_ACCEPTED_FIELDS[wire] ?? null
}

function mergeWithGuest(declared, accepted) {
    const allowed = new Set(accepted)
    const fields = {}
    const covered = new Set()
    for (const [name, spec] of Object.entries(declared?.fields ?? {})) {
        const aliases = (spec.aliases ?? []).filter((alias) => allowed.has(alias))
        const primary = allowed.has(name) ? name : aliases.shift()
        if (primary === undefined) continue
        fields[primary] = { ...spec, ...(aliases.length ? { aliases } : {}) }
        if (!aliases.length) delete fields[primary].aliases
        covered.add(primary)
        for (const alias of aliases) covered.add(alias)
    }
    for (const name of accepted) if (!covered.has(name)) fields[name] = { type: 'any', description: GUEST_FIELD_DESCRIPTION }
    const required = (declared?.required ?? []).filter((name) => name in fields)
    return { required, fields }
}

export function verbBodySchema(verb) {
    const row = tableRow(verb)
    const accepted = guestFields(row)
    const declared = accepted ? mergeWithGuest(row?.body, accepted) : row?.body
    if (!declared) return { declared: false, note: UNDECLARED_NOTE }
    return {
        declared: true,
        verb,
        ...(accepted ? { source: `rs-plugkit@${GUEST_BODY_SOURCE.sha.slice(0, 7)}` } : {}),
        required: declared.required,
        fields: declared.fields,
    }
}

export function describeBodyField(schema, name) {
    if (!schema.declared) return null
    const direct = schema.fields[name] ?? DISPATCH_BODY_FIELDS[name]
    if (direct) return { name, ...direct }
    for (const [field, spec] of Object.entries(schema.fields)) {
        if ((spec.aliases ?? []).includes(name)) return { name: field, ...spec }
    }
    return null
}

export function renderBodyHint(verb, fieldName) {
    const schema = verbBodySchema(verb)
    if (!schema.declared) return `${verb} declares no body schema in gm-mcp; ${UNDECLARED_NOTE}`
    const named = fieldName ? describeBodyField(schema, fieldName) : null
    if (named) {
        const aliases = named.aliases?.length ? ` (aliases ${named.aliases.join(', ')})` : ''
        const values = named.enum ? `, one of ${named.enum.join(' | ')}` : ''
        const required = schema.required.includes(named.name) ? 'required' : 'optional'
        return `${verb} body field "${named.name}"${aliases}: ${required} ${named.type}${values} -- ${named.description}`
    }
    const render = (name) => {
        const spec = schema.fields[name]
        const values = spec.enum ? ` one of ${spec.enum.join('|')}` : ''
        return `${name}${schema.required.includes(name) ? '*' : ''}:${spec.type}${values}`
    }
    return `${verb} body accepts ${Object.keys(schema.fields).map(render).join(', ')} (* = required)`
}

export function bodyShapeLine(verb) {
    const schema = verbBodySchema(verb)
    if (!schema.declared) return ''
    const names = Object.keys(schema.fields).map((name) => (schema.required.includes(name) ? name : `${name}?`))
    return ` Body fields: ${names.join(', ')}.`
}
