#!/usr/bin/env node
// Writes src/fast-manifest.js: the initialize and tools/list replies the real server produces, so the
// cold stdio path can answer them without loading the MCP SDK. Run by build.mjs before bundling.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { LATEST_PROTOCOL_VERSION } from '@modelcontextprotocol/sdk/types.js'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const { createServer } = await import(pathToFileURL(path.join(root, 'src', 'mcp-server.js')).href)

const replies = new Map()
const transport = {
    onmessage: undefined,
    onclose: undefined,
    onerror: undefined,
    start: async () => {},
    close: async () => {},
    send: async (message) => { if (message.id !== undefined) replies.set(message.id, message) },
}
const server = createServer()
await server.connect(transport)
const clientInfo = { name: 'gm-fast-manifest', version: '0' }
transport.onmessage({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: LATEST_PROTOCOL_VERSION, capabilities: {}, clientInfo } })
for (let i = 0; i < 500 && !replies.has(1); i++) await new Promise(resolve => setTimeout(resolve, 5))
transport.onmessage({ jsonrpc: '2.0', method: 'notifications/initialized' })
transport.onmessage({ jsonrpc: '2.0', id: 2, method: 'tools/list', params: {} })
for (let i = 0; i < 500 && !replies.has(2); i++) await new Promise(resolve => setTimeout(resolve, 5))
const init = replies.get(1)?.result
const tools = replies.get(2)?.result
if (!init || !tools) throw new Error('fast manifest: the server did not answer initialize and tools/list')
const body = JSON.stringify({ protocolVersion: LATEST_PROTOCOL_VERSION, initialize: init, tools }, null, 1)
writeFileSync(path.join(root, 'src', 'fast-manifest.js'), `// Generated by scripts/build-fast-manifest.mjs. Do not edit.\nexport const FAST_MANIFEST = ${body}\n`)
console.log(`fast-manifest: protocol=${LATEST_PROTOCOL_VERSION} tools=${tools.tools.length}`)
process.exit(0)
