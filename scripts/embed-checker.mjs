#!/usr/bin/env node
// Embeds the secrets checker into src/checker-snapshot.js as CHECKER_SOURCE. The source is
// scripts/check-staged-secrets.mjs in the parent gm checkout when present, else the same path on
// AnEntrypoint/gm main. publish_on_origin writes that text to its work dir and runs it with cwd set
// to the target repo. A fetch failure or invalid UTF-8 refuses the run: exit 1, file left untouched.
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const RAW_URL = 'https://raw.githubusercontent.com/AnEntrypoint/gm/main/scripts/check-staged-secrets.mjs'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const LOCAL = path.resolve(HERE, '..', 'scripts', 'check-staged-secrets.mjs')
const OUT_PATH = path.resolve(HERE, '..', 'src', 'checker-snapshot.js')
const FETCH_TIMEOUT_MS = 30_000

// JSON.stringify output with every non-ASCII UTF-16 code unit written as a \uXXXX escape.
const asciiJson = (value) => JSON.stringify(value).replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)

async function loadChecker() {
    if (existsSync(LOCAL)) return { from: LOCAL, bytes: readFileSync(LOCAL) }
    const response = await fetch(RAW_URL, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) })
    if (!response.ok) throw new Error(`HTTP ${response.status} for ${RAW_URL}`)
    return { from: RAW_URL, bytes: Buffer.from(await response.arrayBuffer()) }
}

const { from, bytes } = await loadChecker()
const text = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes)
const sha256 = createHash('sha256').update(bytes).digest('hex')
const source = [
    `// Generated by scripts/embed-checker.mjs from ${from === LOCAL ? 'scripts/check-staged-secrets.mjs in this checkout' : RAW_URL}.`,
    `// Checker sha256: ${sha256}. Do not edit by hand; rerun scripts/embed-checker.mjs.`,
    `export const CHECKER_SOURCE = ${asciiJson(text)}`,
    '',
].join('\n')
const tmp = `${OUT_PATH}.tmp-${process.pid}`
writeFileSync(tmp, source, 'utf8')
renameSync(tmp, OUT_PATH)
console.log(`embedded checker from ${from} (sha256 ${sha256}, ${bytes.length} bytes)`)
